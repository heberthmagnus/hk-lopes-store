import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = fs.readFileSync('src/lib/admin-analytics.ts', 'utf8');
const exports = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports, Intl, Date, Map });
const { metrics, dailySeries, salesInRange, comparison, productionCost, shiftDay } = exports;
const sales = [{ created_at: '2026-11-02T01:00:00Z', total_amount: 90, discount_amount: 10, payment_fee_value: 5, items: [{ quantity: 2, cost_price_snapshot: 20 }] }];
const m = metrics(sales);
assert.equal(m.revenue, 90); assert.equal(m.cost, 40); assert.equal(m.gross, 50); assert.equal(m.contribution, 45);
assert.equal(metrics([]).margin, null); assert.equal(metrics([]).ticket, null);
assert.equal(salesInRange(sales, '2026-11-01', '2026-11-01').length, 1);
assert.equal(salesInRange(sales, '2026-11-02', '2026-11-02').length, 0);
assert.equal(dailySeries(sales, '2026-10-31', '2026-11-02').length, 3);
assert.equal(dailySeries(sales, '2026-10-31', '2026-11-02')[0].value, 0);
assert.equal(comparison(100, 0), null); assert.equal(comparison(150, 100), 50);
assert.equal(shiftDay('2026-01-01', -1), '2025-12-31');
const cost = productionCost({ grams: 100, kgPrice: 100, hours: 2, kw: .1, energy: 1, machine: 1, extras: 3, loss: 10, price: 50, fee: 5 });
assert.ok(Math.abs(cost.cost - 16.2) < .0001); assert.equal(cost.fee, 2.5); assert.ok(Math.abs(cost.profit - 31.3) < .0001);
assert.ok(metrics([{ ...sales[0], total_amount: 10 }]).gross < 0);
console.log('Indicadores: 16 verificações passaram (custos, taxas, zeros, perdas, datas e comparação).');
